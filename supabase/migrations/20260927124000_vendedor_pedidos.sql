-- ============================================================
-- ETAPA 4 - VENDEDOR / PEDIDOS
-- App Gestion Comercial
-- Fecha: 27/09/2026
-- ============================================================
--
-- Principios:
-- 1. El pedido conserva las condiciones comerciales originales.
-- 2. El stock local en 0 NO impide vender.
-- 3. Un producto deshabilitado por Central NO puede venderse.
-- 4. El vendedor no calcula precios manualmente.
-- 5. Los pedidos no se eliminan: conservan historial.
-- 6. Una vez que el pedido entra en operación, Comercial no lo
--    modifica directamente.
-- 7. Las incidencias operativas se incorporarán al circuito
--    correspondiente sin destruir el pedido original.
-- ============================================================


-- ------------------------------------------------------------
-- ESTADOS DEL PEDIDO
-- ------------------------------------------------------------

create type public.order_status as enum (
  'BORRADOR',
  'ALERTA',
  'PENDIENTE',
  'GUARDADO',
  'ATENDIDO',
  'RECHAZADO',
  'ENTREGADO'
);


-- ------------------------------------------------------------
-- PEDIDOS
-- ------------------------------------------------------------

create table public.orders (
  id bigint generated by default as identity primary key,

  client_id bigint not null
    references public.clients(id),

  seller_id uuid not null
    references public.profiles(id),

  estado public.order_status not null default 'BORRADOR',

  fecha_pedido timestamptz not null default now(),

  fecha_entrega date,

  -- Un pedido guardado puede quedar programado para otro día.
  fecha_liberacion timestamptz,

  -- Si existe una alerta de precio, la liberación automática
  -- queda detenida hasta resolverla.
  alerta_precio boolean not null default false,

  observaciones text,

  -- Datos de cierre/rechazo.
  motivo_rechazo text,
  rechazado_at timestamptz,
  rechazado_por uuid references public.profiles(id),

  entregado_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint orders_guardado_fecha_check
    check (
      estado <> 'GUARDADO'
      or fecha_entrega is not null
    ),

  constraint orders_rechazado_motivo_check
    check (
      estado <> 'RECHAZADO'
      or (
        motivo_rechazo is not null
        and btrim(motivo_rechazo) <> ''
      )
    )
);


create index orders_client_id_idx
  on public.orders(client_id);

create index orders_seller_id_idx
  on public.orders(seller_id);

create index orders_estado_idx
  on public.orders(estado);

create index orders_fecha_entrega_idx
  on public.orders(fecha_entrega);


-- ------------------------------------------------------------
-- DETALLE DEL PEDIDO
-- ------------------------------------------------------------
--
-- Además de las FK, guardamos snapshots.
-- De esta manera, si mañana cambia el nombre, presentación,
-- precio o promoción, el pedido histórico NO cambia.
-- ------------------------------------------------------------

create table public.order_items (
  id bigint generated by default as identity primary key,

  order_id bigint not null
    references public.orders(id),

  presentation_id bigint not null
    references public.product_presentations(id),

  cantidad integer not null
    check (cantidad > 0),

  -- Snapshot del producto/presentación.
  product_codigo_snapshot text not null,
  product_nombre_snapshot text not null,
  presentation_codigo_snapshot text not null,
  presentation_nombre_snapshot text not null,

  -- Condición económica original.
  precio_unitario numeric(14,2) not null
    check (precio_unitario >= 0),

  -- Promoción aplicada, si corresponde.
  promotion_id bigint
    references public.promotions(id),

promotion_nombre_snapshot text,

promotion_benefit_type_snapshot public.promotion_benefit_type,

  descuento_porcentaje numeric(7,4)
    check (
      descuento_porcentaje is null
      or (
        descuento_porcentaje >= 0
        and descuento_porcentaje <= 100
      )
    ),

  cantidad_bonificada integer not null default 0
    check (cantidad_bonificada >= 0),

  -- Total correspondiente a las unidades pagas.
  subtotal numeric(16,2) generated always as
    (
      round(
        (
          cantidad * precio_unitario
        ) *
        (
          1 - coalesce(descuento_porcentaje, 0) / 100
        ),
        2
      )
    ) stored,

  created_at timestamptz not null default now()
);


create index order_items_order_id_idx
  on public.order_items(order_id);

create index order_items_presentation_id_idx
  on public.order_items(presentation_id);


